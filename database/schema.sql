CREATE DATABASE IF NOT EXISTS ashwamedh CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE ashwamedh;

CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, email VARCHAR(190) NOT NULL UNIQUE,
 name VARCHAR(120) NOT NULL, password_hash VARCHAR(255) NOT NULL,
 role ENUM('student','teacher','course_creator','reviewer','timetable_manager','accounts','admin') NOT NULL DEFAULT 'student',
 phone VARCHAR(30) NOT NULL DEFAULT '', photo VARCHAR(255) NOT NULL DEFAULT '',
 education VARCHAR(200) NOT NULL DEFAULT '', date_of_birth DATE NULL,
 country VARCHAR(100) NOT NULL DEFAULT '', state VARCHAR(100) NOT NULL DEFAULT '',
 district VARCHAR(100) NOT NULL DEFAULT '', janpad VARCHAR(100) NOT NULL DEFAULT '',
 tehsil VARCHAR(100) NOT NULL DEFAULT '', village VARCHAR(120) NOT NULL DEFAULT '',
 postal_code VARCHAR(12) NOT NULL DEFAULT '', gurukul_branch VARCHAR(160) NOT NULL DEFAULT '',
 email_verified_at TIMESTAMP NULL, phone_verified_at TIMESTAMP NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS categories (
 id VARCHAR(100) PRIMARY KEY, parent_id VARCHAR(100) NULL, system VARCHAR(30) NOT NULL,
 title VARCHAR(190) NOT NULL, image VARCHAR(255) NOT NULL DEFAULT '', position INT NOT NULL DEFAULT 0,
 filters JSON NULL, INDEX(parent_id,position)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS courses (
 id VARCHAR(100) PRIMARY KEY, category_id VARCHAR(100) NULL, title VARCHAR(255) NOT NULL,
 description TEXT NOT NULL, image VARCHAR(255) NOT NULL DEFAULT '', instructor VARCHAR(190) NOT NULL DEFAULT 'Ashwamedh Gurukul',
 filters JSON NULL, published TINYINT(1) NOT NULL DEFAULT 1, featured TINYINT(1) NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, INDEX(category_id,published),
 FULLTEXT KEY course_search(title,description)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS chapters (
 id VARCHAR(160) PRIMARY KEY, course_id VARCHAR(100) NOT NULL, title VARCHAR(255) NOT NULL,
 position INT NOT NULL DEFAULT 0, FOREIGN KEY(course_id) REFERENCES courses(id) ON DELETE CASCADE,
 INDEX(course_id,position)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS lessons (
 id VARCHAR(160) PRIMARY KEY, chapter_id VARCHAR(160) NOT NULL, title VARCHAR(255) NOT NULL,
 body MEDIUMTEXT NOT NULL, hindi MEDIUMTEXT NOT NULL, english MEDIUMTEXT NOT NULL,
 video_url TEXT NOT NULL, pdf_url TEXT NOT NULL, ppt_url TEXT NOT NULL, source_url TEXT NOT NULL,
 duration INT NOT NULL DEFAULT 0, position INT NOT NULL DEFAULT 0, is_free TINYINT(1) NOT NULL DEFAULT 1,
 FOREIGN KEY(chapter_id) REFERENCES chapters(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS questions (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, lesson_id VARCHAR(160) NOT NULL,
 prompt TEXT NOT NULL, options JSON NOT NULL, answer TINYINT UNSIGNED NOT NULL,
 explanation TEXT NOT NULL, FOREIGN KEY(lesson_id) REFERENCES lessons(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS progress (
 user_id INT UNSIGNED NOT NULL, lesson_id VARCHAR(160) NOT NULL, completed TINYINT(1) NOT NULL DEFAULT 0,
 seconds INT NOT NULL DEFAULT 0, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,lesson_id), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(lesson_id) REFERENCES lessons(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS bookmarks (
 user_id INT UNSIGNED NOT NULL, course_id VARCHAR(100) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,course_id), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(course_id) REFERENCES courses(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS quiz_attempts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL, lesson_id VARCHAR(160) NOT NULL,
 score INT NOT NULL, total INT NOT NULL, feedback JSON NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(lesson_id) REFERENCES lessons(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sessions (
 token CHAR(64) PRIMARY KEY, user_id INT UNSIGNED NULL, csrf CHAR(64) NOT NULL,
 expires_at TIMESTAMP NOT NULL, INDEX(expires_at), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS registration_verifications (
 id CHAR(36) PRIMARY KEY, session_token CHAR(64) NOT NULL, channel ENUM('email','phone') NOT NULL,
 destination VARCHAR(190) NOT NULL, code_hash VARCHAR(255) NOT NULL, sent_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 expires_at TIMESTAMP NOT NULL, delivered_at TIMESTAMP NULL, attempts INT NOT NULL DEFAULT 0,
 verified_at TIMESTAMP NULL, verified_until TIMESTAMP NULL, UNIQUE KEY(session_token,channel), INDEX(expires_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rate_limits (
 `key` VARCHAR(190) PRIMARY KEY, `count` INT NOT NULL DEFAULT 1, expires_at TIMESTAMP NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS reset_tokens (
 token CHAR(64) PRIMARY KEY, user_id INT UNSIGNED NOT NULL, expires_at TIMESTAMP NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS memberships (
 user_id INT UNSIGNED PRIMARY KEY, expires_at TIMESTAMP NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS schema_versions (
 version VARCHAR(100) PRIMARY KEY, applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS workspace_feedback (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, item_id VARCHAR(100) NOT NULL,
 author_id INT UNSIGNED NOT NULL, message TEXT NOT NULL, action VARCHAR(40) NOT NULL DEFAULT 'comment',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(item_id) REFERENCES workspace_items(id) ON DELETE CASCADE,
 FOREIGN KEY(author_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS learning_certificates (
 id VARCHAR(100) PRIMARY KEY, user_id INT UNSIGNED NOT NULL, attempt_id INT UNSIGNED NOT NULL UNIQUE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(attempt_id) REFERENCES quiz_attempts(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS paper_attempts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL, paper_id VARCHAR(100) NOT NULL,
 score INT NOT NULL, total INT NOT NULL, feedback JSON NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE, FOREIGN KEY(paper_id) REFERENCES workspace_items(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS assignment_submissions (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL, assignment_id VARCHAR(100) NOT NULL,
 body TEXT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, UNIQUE KEY(user_id,assignment_id),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE, FOREIGN KEY(assignment_id) REFERENCES workspace_items(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS study_paths (
 user_id INT UNSIGNED NOT NULL, system VARCHAR(30) NOT NULL, category_id VARCHAR(100) NOT NULL,
 filters JSON NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,system), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(category_id) REFERENCES categories(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS user_avatars (
 id VARCHAR(100) PRIMARY KEY, user_id INT UNSIGNED NOT NULL UNIQUE, image MEDIUMBLOB NOT NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS workspace_items (
 id VARCHAR(100) PRIMARY KEY, owner_id INT UNSIGNED NOT NULL, kind VARCHAR(40) NOT NULL,
 title VARCHAR(255) NOT NULL, data JSON NOT NULL, status ENUM('draft','submitted','revision','approved','published') NOT NULL DEFAULT 'draft',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(owner_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
